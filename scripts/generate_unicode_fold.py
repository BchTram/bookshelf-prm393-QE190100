"""Generate Unicode simple fold tables and the Rules canonical guard.
Rules lower() is ASCII-only; RE2 (?i) matches Unicode simple case variants.
Multi-codepoint expansions and Unicode normalization are intentionally absent.
"""
import json
from pathlib import Path
import unicodedata

root = Path(__file__).resolve().parents[1]
fold = {}
for point in range(0x110000):
    char = chr(point)
    mapped = char.casefold()
    if len(mapped) != 1:
        mapped = char.lower()
    if len(mapped) == 1 and mapped != char:
        fold[point] = ord(mapped)
lines = ['// Generated by scripts/generate_unicode_fold.py.',
         f'// Unicode {unicodedata.unidata_version}; single-codepoint folds.',
         'const unicodeSimpleFold = <int, int>{']
lines.extend(f'  {key}: {value},' for key, value in fold.items())
lines.append('};')
(root / 'lib/utilities/unicode_fold.dart').write_text('\n'.join(lines) + '\n', encoding='utf-8')
(root / 'rules_test/unicode_fold.json').write_text(json.dumps(fold), encoding='utf-8')
points = sorted(fold)
ranges = []
start = previous = points[0]
for point in points[1:] + [None]:
    if point is not None and point == previous + 1:
        previous = point
        continue
    ranges.append(chr(start) if start == previous else chr(start) + '-' + chr(previous))
    start = previous = point
pattern = '[^' + ''.join(ranges) + ']*'
target = root / 'firestore.rules'
rules = target.read_text(encoding='utf-8')
marker_start = '// BEGIN GENERATED CANONICAL GUARD'
marker_end = '// END GENERATED CANONICAL GUARD'
before, remainder = rules.split(marker_start, 1)
_, after = remainder.split(marker_end, 1)
rules = before + marker_start + '\n    function canonical(s) { return s.matches(' + json.dumps(pattern, ensure_ascii=False) + '); }\n    ' + marker_end + after
compat = json.loads((root / 'rules_test/re2_compatibility.json').read_text())
replacement = 's' + ''.join('.replace(' + json.dumps(chr(int(k)), ensure_ascii=False) + ', ' + json.dumps(chr(v), ensure_ascii=False) + ')' for k, v in compat.items())
rules = rules.replace('// BEGIN GENERATED RE2 COMPATIBILITY' + rules.split('// BEGIN GENERATED RE2 COMPATIBILITY', 1)[1].split('// END GENERATED RE2 COMPATIBILITY', 1)[0] + '// END GENERATED RE2 COMPATIBILITY', '// BEGIN GENERATED RE2 COMPATIBILITY\n    function compatible(s) { return ' + replacement + '; }\n    // END GENERATED RE2 COMPATIBILITY')
target.write_text(rules, encoding='utf-8')
print(f'Generated {len(fold)} folds from Unicode {unicodedata.unidata_version}')
